# Repetições numéricas:
for c in range(0, 6):
    print(c) # Usar a variável da estrutura de repetição faz uma lista numérica.
print('FIM')

for c in range(1, 7): # Para fazer uma lista numérica que comece pelo número 1 e termine no 6, precisamos terminar o range no 7 (um número a frente).
    print(c)
print('FIM')