# Particionando strings:
frase = 'Curso em Vídeo Python'
print(frase, '\n')

# Frase na posição 3:
print(frase[3], '\n')

# Frase da posição 3 à 12
print(frase[3:13], '\n')

# Frase do início até a posição 12:
print(frase[:13], '\n')

# Frase da posição 12 até o final:
print(frase[13:], '\n')

# Frase da posição 1 à posição 14 de a cada dois caracteres:
print(frase[1:15:2], '\n')

# Frase da posição 1 até o final a cada dois caracteres:
print(frase[1::2], '\n')

# Frase do início ao final à cada 2 caracteres:
print(frase[::2], '\n')
