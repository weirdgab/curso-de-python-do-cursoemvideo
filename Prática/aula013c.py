# Mudando tipos de iterações

# Criando contagem regressiva.
for c in range(6, 0, -1): #  Terceiro valor na função range define o tipo de iteração.
    print(c) 
print('FIM')

# Repetição pulando valores.
for c in range(1, 7, 2): # Terceiro valor define contagem de 2 em dois valores.
    print(c)
print('FIM')